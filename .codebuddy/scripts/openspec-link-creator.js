#!/usr/bin/env node
/**
 * OpenSpec Link Creator - 自动创建链接和映射表
 * 
 * 用途: 在multi-plan的Phase 4.5中使用,自动建立计划与OpenSpec变更之间的链接
 * 
 * 使用方式:
 *   node openspec-link-creator.js create <planPath> <openspecPath>
 *   node openspec-link-creator.js validate <planPath>
 */

const fs = require('fs');
const path = require('path');

/**
 * 创建前向引用 - 在计划文件中添加OpenSpec引用
 */
function createForwardLink(planPath, openspecPath) {
  if (!fs.existsSync(planPath)) {
    throw new Error(`计划文件不存在: ${planPath}`);
  }

  const planContent = fs.readFileSync(planPath, 'utf-8');

  // 检查是否已经存在OpenSpec引用
  if (planContent.includes('关联 OpenSpec 变更')) {
    console.log('✓ 前向引用已存在,跳过创建');
    return;
  }

  // 计算相对路径
  const planDir = path.dirname(planPath);
  const relativeOpenspecPath = path.relative(planDir, openspecPath);

  // 在文件开头添加OpenSpec引用
  const forwardLink = `
---

**关联 OpenSpec 变更**: \`${relativeOpenspecPath}\`

---

`;
  fs.writeFileSync(planPath, forwardLink + planContent);
  console.log(`✓ 前向引用已创建: ${planPath}`);
}

/**
 * 创建后向引用 - 在proposal.md中添加计划引用
 */
function createBackwardLink(openspecPath, planPath) {
  const proposalPath = path.join(openspecPath, 'proposal.md');
  if (!fs.existsSync(proposalPath)) {
    console.warn('⚠ proposal.md 不存在,跳过后向引用创建');
    return;
  }

  const proposalContent = fs.readFileSync(proposalPath, 'utf-8');

  // 检查是否已经存在计划引用
  if (proposalContent.includes('原始计划')) {
    console.log('✓ 后向引用已存在,跳过创建');
    return;
  }

  // 计算相对路径
  const openspecDir = openspecPath;
  const relativePlanPath = path.relative(openspecDir, planPath);

  // 在文件开头添加计划引用
  const backwardLink = `
---

**原始计划**: \`${relativePlanPath}\`

---

`;
  fs.writeFileSync(proposalPath, backwardLink + proposalContent);
  console.log(`✓ 后向引用已创建: ${proposalPath}`);
}

/**
 * 创建映射表 .plan-mapping.md
 */
function createMappingTable(openspecPath, planPath) {
  const mappingPath = path.join(openspecPath, '.plan-mapping.md');
  
  if (fs.existsSync(mappingPath)) {
    console.log('✓ 映射表已存在,跳过创建');
    return;
  }

  const planDir = path.dirname(planPath);
  const openspecDir = openspecPath;
  const changeName = path.basename(openspecPath);
  const planName = path.basename(planPath, '.md');

  // 计算相对路径
  const relativePlanPath = path.relative(openspecDir, planPath);
  const relativeOpenspecPath = path.relative(planDir, openspecPath);

  const mappingContent = `# Plan Mapping Table

## Multi-Plan → OpenSpec Artifact Mapping

| Plan File | OpenSpec Change | Artifact Type | Relative Path | Status |
|-----------|----------------|---------------|---------------|--------|
| \`${planName}.md\` | ${changeName} | proposal.md | proposal.md | ✓ Active |
| \`${planName}.md\` | ${changeName} | specs/ | specs/ | ✓ Active |
| \`${planName}.md\` | ${changeName} | design.md | design.md | ✓ Active |
| \`${planName}.md\` | ${changeName} | tasks.md | tasks.md | ✓ Active |

## Link Verification

- **Forward Link**: Plan → OpenSpec (via proposal metadata)
- **Backward Link**: Proposal → Plan (via proposal header)
- **Mapping Table**: This file

## Change Metadata

- **Change Name**: ${changeName}
- **Plan Name**: ${planName}
- **Mapping Mode**: One-to-One (1:1)
- **Created**: ${new Date().toISOString()}

## Artifact Details

### proposal.md
- Path: proposal.md
- Contains: Objectives, scope, acceptance criteria
- Links to: \`${relativePlanPath}\`

### specs/
- Path: specs/
- Contains: Detailed specifications
- Format: Individual spec files

### design.md
- Path: design.md
- Contains: Architecture, technical decisions

### tasks.md
- Path: tasks.md
- Contains: Granular task list with checkboxes
- Tracking: Progress via checkbox states

---
*Auto-generated by openspec-link-creator.js*
`;

  fs.writeFileSync(mappingPath, mappingContent);
  console.log(`✓ 映射表已创建: ${mappingPath}`);
}

/**
 * 验证所有链接
 */
function validateLinks(planPath) {
  console.log('\n🔍 验证链接完整性...\n');

  if (!fs.existsSync(planPath)) {
    throw new Error(`计划文件不存在: ${planPath}`);
  }

  const planContent = fs.readFileSync(planPath, 'utf-8');
  const planDir = path.dirname(planPath);
  let allValid = true;

  // 1. 检查前向引用
  const openspecRef = planContent.match(/关联 OpenSpec 变更.*?:\s*`([^`]+)`/);
  if (!openspecRef) {
    console.log('❌ 缺少前向引用 (Plan → OpenSpec)');
    allValid = false;
  } else {
    const openspecPath = path.resolve(planDir, openspecRef[1]);
    if (!fs.existsSync(openspecPath)) {
      console.log(`❌ 前向引用指向不存在的路径: ${openspecRef[1]}`);
      allValid = false;
    } else {
      console.log(`✓ 前向引用有效: ${openspecRef[1]}`);
    }
  }

  // 2. 检查后向引用
  if (openspecRef && allValid) {
    const openspecPath = path.resolve(planDir, openspecRef[1]);
    const proposalPath = path.join(openspecPath, 'proposal.md');
    
    if (fs.existsSync(proposalPath)) {
      const proposalContent = fs.readFileSync(proposalPath, 'utf-8');
      const planRef = proposalContent.match(/原始计划.*?:\s*`([^`]+)`/);
      
      if (!planRef) {
        console.log('⚠️  缺少后向引用 (Proposal → Plan)');
      } else {
        console.log(`✓ 后向引用有效: ${planRef[1]}`);
      }
    }
  }

  // 3. 检查映射表
  if (openspecRef && allValid) {
    const openspecPath = path.resolve(planDir, openspecRef[1]);
    const mappingPath = path.join(openspecPath, '.plan-mapping.md');
    
    if (!fs.existsSync(mappingPath)) {
      console.log('⚠️  缺少映射表 (.plan-mapping.md)');
      allValid = false;
    } else {
      console.log('✓ 映射表存在');
    }
  }

  if (allValid) {
    console.log('\n✅ 所有链接验证通过\n');
  } else {
    console.log('\n⚠️  存在链接问题\n');
  }

  return allValid;
}

/**
 * 主函数
 */
function main() {
  const args = process.argv.slice(2);
  
  if (args.length < 1) {
    console.log('用法:');
    console.log('  node openspec-link-creator.js create <planPath> <openspecPath>');
    console.log('  node openspec-link-creator.js validate <planPath>');
    process.exit(1);
  }

  const command = args[0];

  try {
    if (command === 'create') {
      if (args.length < 3) {
        throw new Error('create 命令需要 planPath 和 openspecPath 参数');
      }
      
      const planPath = args[1];
      const openspecPath = args[2];
      
      console.log('🔗 创建 OpenSpec 链接...\n');
      createForwardLink(planPath, openspecPath);
      createBackwardLink(openspecPath, planPath);
      createMappingTable(openspecPath, planPath);
      console.log('\n✅ 所有链接创建完成');
      
    } else if (command === 'validate') {
      if (args.length < 2) {
        throw new Error('validate 命令需要 planPath 参数');
      }
      
      const planPath = args[1];
      const isValid = validateLinks(planPath);
      process.exit(isValid ? 0 : 1);
      
    } else {
      throw new Error(`未知命令: ${command}`);
    }
    
  } catch (error) {
    console.error(`❌ 错误: ${error.message}`);
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}

module.exports = {
  createForwardLink,
  createBackwardLink,
  createMappingTable,
  validateLinks
};
